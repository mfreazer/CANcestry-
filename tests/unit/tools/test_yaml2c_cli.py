def test_schema_paths():
    assert schema.schema_path("fsm", SCHEMA_DIR).endswith(
        "fsm-0.3.0.schema.json")
    assert schema.schema_path("codec", SCHEMA_DIR).endswith(
        "codec-map-0.3.0.schema.json")
    with pytest.raises(Yaml2cError):
        schema.schema_path("recipe", SCHEMA_DIR)
    with pytest.raises(Yaml2cError):
        schema.schema_path("fsm", "nowhere")


def test_load_schema():
    document = schema.load_schema("fsm", SCHEMA_DIR)
    assert document["$id"].endswith("fsm-0.3.0.schema.json")


def test_validate_document_passes_and_fails(fsm_file):
    from tools.yaml2c.common import loader_view
    from tools.yaml2c.yaml2c import compose_document

    view = loader_view(compose_document(str(fsm_file)))
    assert schema.validate_document(view, "fsm", str(SCHEMA_DIR),
                                    "doc.yaml") is None
    view["schema_version"] = "9.9.9"
    with pytest.raises(Yaml2cError) as info:
        schema.validate_document(view, "fsm", str(SCHEMA_DIR), "doc.yaml")
    assert "doc.yaml violates fsm-0.3.0.schema.json" in str(info.value)


def test_validate_document_without_jsonschema(fsm_file, monkeypatch):
    """The gate refuses loudly when jsonschema is absent (fail closed):
    generating unchecked C would replace the runtime loader's checks."""
    import sys

    from tools.yaml2c.common import loader_view
    from tools.yaml2c.yaml2c import compose_document

    monkeypatch.setitem(sys.modules, "jsonschema", None)
    view = loader_view(compose_document(str(fsm_file)))
    with pytest.raises(Yaml2cError) as info:
        schema.validate_document(view, "fsm", str(SCHEMA_DIR))
    assert "jsonschema" in str(info.value)


