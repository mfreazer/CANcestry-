"""In-process CLI tests for yaml2c and its schema gate (issue #22).

Running ``main()`` directly (not via subprocess) both pins the exit-code
contract and covers the CLI code paths for the 100% coverage requirement.

Requirements traced: SW-FR-TOOL-001..005.
Test ids: YAML2C-CLI-001..004.
"""

from __future__ import annotations

import json

import pytest

from tools.trace_viewer import trace_format as tf  # noqa: F401  (import time)
from tools.yaml2c import schema
