def test_cli_open_race_exits_two(tmp_path, fsm_file, capsys, monkeypatch):
    """The file passes the existence check but cannot be opened (the
    classic check-then-open race): report a clean usage error."""
    import tools.yaml2c.yaml2c as module

    real_isfile = module.os.path.isfile

    monkeypatch.setattr(module.os.path, "isfile",
                        lambda path: True if path == str(fsm_file)
                        else real_isfile(path))
    import builtins

    real_open = builtins.open

    def fake_open(path, *args, **kwargs):
        if str(path) == str(fsm_file):
            raise IsADirectoryError(21, "Is a directory", str(path))
        return real_open(path, *args, **kwargs)

    monkeypatch.setattr(builtins, "open", fake_open)
    assert cli.main(["--schema-dir", str(SCHEMA_DIR), "--stdout",
                     str(fsm_file)]) == 2
    assert "yaml2c: error:" in capsys.readouterr().err
